"""Standalone evaluation intent, separate from the training schedule."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from specforge.nsp.metrics import parse_bins


class ServingSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")
    url: str
    prompts: str
    model: str
    # Server arguments carry the draft path; /get_model_info only identifies target.
    info_path: str = "/get_server_info"
    checkpoint_field: str = "speculative_draft_model_path"
    temperature: float = Field(default=0, ge=0)
    top_p: float = Field(default=1, gt=0, le=1)
    max_new_tokens: int = Field(default=128, gt=0)
    timeout: float = Field(default=300, gt=0)
    api_key_env: str | None = None
    protocol: Literal["openai", "native"] = "openai"
    concurrency: int = Field(default=1, ge=1, le=1024)
    warmup_requests: int = Field(default=0, ge=0)
    expected_server_args: dict = Field(default_factory=dict)


class EvalSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")
    schema_version: Literal[1] = 1
    recipe: str | None = None
    features: str | None = None
    checkpoint: str = ""
    metrics: list[Literal["loss", "accuracy", "prefix-al", "al", "performance"]] = Field(
        default_factory=lambda: ["loss", "accuracy"]
    )
    group_by: Literal["ctx-len"] | None = None
    ctx_bins: list[int | str] = Field(
        default_factory=lambda: [0, 4096, 8192, 16384, 32768, 65536, 131072, "inf"]
    )
    seed: int = 42
    anchor_chunk_size: int = Field(default=32, gt=0)
    # Captured-prefix origin is explicit: sliced features must provide per-record origins.
    ctx_origin: Literal["record-start"] | None = None
    global_step: int | None = Field(default=None, ge=0)
    total_steps: int | None = Field(default=None, gt=0)
    serving: ServingSpec | None = None
    resolved_recipe: dict | None = None

    @model_validator(mode="after")
    def validate_selection(self):
        if not self.metrics or len(set(self.metrics)) != len(self.metrics):
            raise ValueError("metrics must be a nonempty set without duplicates")
        parse_bins(self.ctx_bins)
        if any(m not in ("al", "performance") for m in self.metrics) and not (self.recipe and self.features):
            raise ValueError("offline metrics require recipe and features")
        if any(m in ("al", "performance") for m in self.metrics) and self.serving is None:
            raise ValueError("serving metrics require a dedicated endpoint and prompts")
        if "al" not in self.metrics and self.serving and self.group_by:
            raise ValueError("serving ctx bins require actual AL cycle telemetry")
        if (
            self.group_by
            and any(m not in ("al", "performance") for m in self.metrics)
            and self.ctx_origin != "record-start"
        ):
            raise ValueError(
                "ctx bins require ctx_origin: record-start; sliced captures must first preserve their prefix origin"
            )
        return self


def load_eval(path, checkpoint, metrics=None, group_by=None, ctx_bins=None):
    if "RANK" in os.environ or int(os.environ.get("WORLD_SIZE", "1")) != 1:
        raise ValueError("standalone eval must run outside torchrun")
    path = Path(path).resolve()
    raw = yaml.safe_load(path.read_text())
    if not isinstance(raw, dict):
        raise ValueError("eval config must be an object")
    if "resolved_recipe" in raw:
        raise ValueError("resolved_recipe is generated by nsp, not an input field")
    raw["checkpoint"] = checkpoint
    if metrics:
        raw["metrics"] = (
            ["loss", "accuracy", "prefix-al", "al"]
            if metrics == "all"
            else metrics.split(",")
        )
    if group_by:
        raw["group_by"] = group_by
    if ctx_bins:
        raw["ctx_bins"] = ctx_bins.split(",")
    for field in ("recipe", "features"):
        if raw.get(field):
            raw[field] = str((path.parent / raw[field]).resolve())
    if raw.get("serving"):
        raw["serving"]["prompts"] = str(
            (path.parent / raw["serving"]["prompts"]).resolve()
        )
    spec = EvalSpec.model_validate(raw)
    if any(m not in ("al", "performance") for m in spec.metrics):
        from specforge.application import resolve_run
        from specforge.config import Config

        recipe = yaml.safe_load(Path(spec.recipe).read_text())
        recipe.setdefault("data", {}).update(
            hidden_states_path=spec.features,
            train_data_path="",
            prompts_path="",
            eval_hidden_states_path="",
            eval_data_path="",
        )
        recipe.setdefault("training", {}).update(
            eval_interval=0, resume_from=None, role="all"
        )
        recipe.setdefault("model", {})["draft_checkpoint_path"] = checkpoint
        recipe["deployment"] = {"mode": "local_colocated"}
        cfg = Config.model_validate(recipe)
        resolved = resolve_run(cfg)
        supported = {"dspark", "deepseek_v41", "dflash"}
        if resolved.algorithm.name not in supported | {"eagle3", "mtp", "domino"}:
            raise ValueError(
                f"standalone evaluation is not implemented for {resolved.algorithm.name}"
            )
        if cfg.training.lk_loss_type == "lambda" or cfg.training.loss_type != "dflash":
            raise ValueError(
                "standalone eval requires an additive objective; LK lambda and D-PACE need their own reducer"
            )
        if (
            spec.group_by or "prefix-al" in spec.metrics
        ) and resolved.algorithm.name not in supported:
            raise ValueError(
                f"anchor ctx bins/prefix-al are not implemented for {resolved.algorithm.name}; supported: {sorted(supported)}"
            )
        if (
            cfg.training.tp_size != 1
            or cfg.training.sp_ulysses_size != 1
            or cfg.training.sp_ring_size != 1
        ):
            raise ValueError("standalone offline evaluation currently requires TP=SP=1")
        spec.resolved_recipe = cfg.model_dump(mode="json")
    return spec
